#!/usr/bin/env python3
"""Generate Sources/FrescobaldiCore/LilyPondWords.swift from python-ly.

Usage: scripts/gen-lilypond-words.py /path/to/python-ly-root > Sources/FrescobaldiCore/LilyPondWords.swift

The word lists come from python-ly's ly/words.py, the pitch names from
ly/pitch/__init__.py (pitchInfo). Run with `python3 -I` semantics: only the
given python-ly checkout is imported.
"""
import sys

sys.path.insert(0, sys.argv[1])
from ly import words, pkginfo  # noqa: E402
from ly.pitch import pitchInfo  # noqa: E402


def pitch_names():
    out = set()
    for info in pitchInfo.values():
        names, accs = info[0], info[1]
        replacements = info[2] if len(info) > 2 else ()
        lang = {n + a for n in names for a in accs}
        # PitchReader rewrites r -> s in sequence, so apply the inverse
        # rewrites until nothing new appears (deutsch: aeses <- ases <- asas).
        while True:
            more = {r + p[len(s):] for s, r in replacements
                    for p in lang if p.startswith(s)}
            if more <= lang:
                break
            lang |= more
        out |= lang
    # Long English syntax: cflat, c-sharp, cflatflat, ...
    for n in "cdefgab":
        for a in ("flat", "sharp", "flatflat", "sharpsharp"):
            out.add(n + a)
            out.add(n + "-" + a)
    out.discard("")
    return out


def swift_set(name, items, doc):
    items = sorted(set(items))
    lines = [f"    /// {doc}", f"    static let {name}: Set<String> = ["]
    row = "       "
    for w in items:
        piece = f' "{w}",'
        if len(row) + len(piece) > 79:
            lines.append(row)
            row = "       "
        row += piece
    lines.append(row)
    lines.append("    ]")
    return "\n".join(lines)


markup = set(words.markupcommands) | set(words.markuplistcommands)
articulations = (set(words.articulations) | set(words.ornaments) | set(words.fermatas)
                 | set(words.instrument_scripts) | set(words.repeat_scripts)
                 | set(words.ancient_scripts))

print(f"""// GENERATED by scripts/gen-lilypond-words.py from python-ly {pkginfo.version}
// (ly/words.py and ly/pitch). Do not edit by hand; regenerate instead.
// python-ly is GPL-2.0-or-later.

enum LilyPondWords {{
{swift_set("keywords", words.lilypond_keywords, "Backslash keywords (`\\score`, `\\header`; `\\new` is a music command).")}

{swift_set("musicCommands", set(words.lilypond_music_commands) | set(words.modes), "Built-in music functions and commands, plus key modes (`\\major`).")}

{swift_set("articulations", articulations, "Articulations, ornaments, fermatas and other scripts (`\\staccato`, `\\trill`).")}

{swift_set("markupCommands", markup, "Markup and markup-list commands (`\\bold`, `\\column`).")}

{swift_set("contexts", words.contexts, "Context names (`Staff`, `Voice`).")}

{swift_set("pitchNames", pitch_names(), "Note names in every input language LilyPond supports.")}
}}""")
